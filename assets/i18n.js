const browserLanguage = /^ja(?:-|$)/i.test(navigator.language || "") ? "ja" : "en";
let language = browserLanguage;

function t(key, values = {}) {
  return (messages[language][key] ?? messages.en[key] ?? key)
    .replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

function applyLanguage(next) {
  language = next === "ja" ? "ja" : "en";
  document.documentElement.lang = language;
  for (const el of document.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const [attribute, dataset] of [["aria-label", "i18nAria"], ["placeholder", "i18nPlaceholder"]]) {
    for (const el of document.querySelectorAll(`[data-${dataset.replace(/[A-Z]/g, c => "-" + c.toLowerCase())}]`)) {
      el.setAttribute(attribute, t(el.dataset[dataset]));
    }
  }
}
window.FontFourierI18n = { browserLanguage, applyLanguage, t };
